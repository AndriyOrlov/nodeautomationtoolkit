"""Правило шапки §: частина, названа в шапці, поширюється на пункти розділу.

Три форми, які трапляються в наказах:

A. шапка називає частину + «ПРИЗНАЧИТИ до цього самого полку», пункти частин не називають;
B. шапка каже ЗВІДКИ (`із 66 полку зв'язку 55 армійського корпусу`), пункт каже КУДИ;
C. навпаки: шапка каже КУДИ, пункт каже ЗВІДКИ.

Відмінкові форми тут написані ВРУЧНУ і мають бути справжніми: дописати закінчення
до називного («загін» + «у») не можна — стемер зводить «загін» до «загон», і такий
підроблений рядок не знаходиться. Через це попередній варіант цієї перевірки давав
хибну тривогу.
"""
import sys

sys.path.insert(0, "src")
sys.stdout.reconfigure(encoding="utf-8")

from nodeautomationtoolkit.builtin_nodes.recipient_mapping import map_military_units  # noqa: E402


def E(name, cipher, abbr, corps=""):
    return {"open_name": name, "cipher": cipher, "abbreviation": abbr, "corps": corps,
            "recipient_to": f"Командиру військової частини {cipher}",
            "destination_where": "м. Тест"}


REPAIR = "46 окремий ремонтно-відновлювальний полк"
SIGNAL = "66 полк зв'язку"
CORPS = "55 армійський корпус"
OTHER = "77 окремий тестовий загін"

MAPPING = {
    REPAIR: E(REPAIR, "А0046", "46 орвп"),
    SIGNAL: E(SIGNAL, "А0066", "66 пз", corps="55 АК"),
    CORPS: E(CORPS, "А0055", "55 АК"),
    OTHER: E(OTHER, "А0077", "77 отз"),
}

SIGNER = "\nКомандир військової частини А0001\nполковник   Петро ТЕСТОВИЙ\n"

CASES = [
    ("A. шапка: частина + «до цього самого полку», пункти без частини",
     "§ 1\n"
     "Відповідно до пунктів 1 та 2 Положення про проходження громадянами України "
     "військової служби у Збройних Силах України нижчепойменованих осіб офіцерського "
     "складу 46 окремого ремонтно-відновлювального полку ЗВІЛЬНИТИ з займаних посад "
     "і ПРИЗНАЧИТИ до цього самого полку:\n"
     "\n1. Майора ТЕСТЕНКА Андрія Борисовича, начальника автомобільної служби "
     "технічної частини – НАЧАЛЬНИКОМ СЛУЖБИ ВІЙСЬКОВОЇ ТЕХНІКИ ОЗБРОЄННЯ ЛОГІСТИКИ.\n"
     "\n2. Капітана ПРИКЛАДЕНКА Богдана Омеляновича, начальника служби "
     "пально-мастильних матеріалів тилу – НАЧАЛЬНИКОМ СЛУЖБИ ПАЛЬНО-МАСТИЛЬНИХ "
     "МАТЕРІАЛІВ ТИЛУ ЛОГІСТИКИ.\n",
     {"46 орвп А0046"}),

    ("B. шапка: ЗВІДКИ (полк корпусу), пункт каже КУДИ",
     "§ 2\n"
     "Відповідно до пункту 3 Положення нижчепойменованих осіб офіцерського складу "
     "із 66 полку зв'язку 55 армійського корпусу ЗВІЛЬНИТИ з займаних посад "
     "і ПРИЗНАЧИТИ:\n"
     "\n3. Майора ЗРАЗКОВА Василя Васильовича, офіцера – ОФІЦЕРОМ "
     "77 окремого тестового загону.\n",
     {"55 АК А0055", "77 отз А0077"}),

    ("C. шапка: КУДИ (полк корпусу), пункт каже ЗВІДКИ",
     "§ 3\n"
     "Відповідно до пункту 4 Положення нижчепойменованих осіб офіцерського складу "
     "ЗВІЛЬНИТИ з займаних посад і ПРИЗНАЧИТИ до 66 полку зв'язку "
     "55 армійського корпусу:\n"
     "\n4. Майора ЗРАЗКОВА Василя Васильовича, офіцера 77 окремого тестового "
     "загону – ОФІЦЕРОМ.\n",
     {"55 АК А0055", "77 отз А0077"}),
]

bad = 0
for title, body, expected in CASES:
    result = map_military_units(text=body + SIGNER, mapping=MAPPING)
    units = result.get("unit_paragraphs", {})
    got = set(units)
    ok = got == expected
    if not ok:
        bad += 1
    print(f"\n{title}")
    print(f"   очікувано: {sorted(expected)}")
    print(f"   фактично : {sorted(got)}  {'OK' if ok else '<-- ХИБА'}")
    for key, data in units.items():
        print(f"      {key}: пункти {[i.get('label') for i in data.get('items', [])]}")
    if result.get("unmatched_items"):
        print(f"      БЕЗ АДРЕСАТА: {[i.get('label') for i in result['unmatched_items']]}")

print(f"\nрозбіжностей: {bad} з {len(CASES)}")
