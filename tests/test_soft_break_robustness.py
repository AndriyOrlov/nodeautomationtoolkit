"""Мʼякий перенос усередині фрази не повинен ламати розбір пункту.

У наказах текст рясно розривають Shift+Enter — просто там, де закінчився рядок.
`read_document_text` розбиває такий абзац на кілька «рядків», і будь-яка
перевірка, що дивиться на ОДИН рядок, промахується. Тут зібрані випадки, які
через це вже ламалися на реальних наказах.
"""

import sys
from pathlib import Path

import pytest

SRC_PATH = Path(__file__).resolve().parents[1] / "src"
if str(SRC_PATH) not in sys.path:
    sys.path.insert(0, str(SRC_PATH))

from nodeautomationtoolkit.builtin_nodes.recipient_mapping import (
    _extract_tck_sender,
    _get_item_main_text,
    map_military_units,
)

UNIT = "267 окрема механізована бригада"
OBLAST_TCK = (
    "Рівненський обласний територіальний центр комплектування та соціальної підтримки"
)
MAPPING = {
    UNIT: {
        "open_name": UNIT,
        "cipher": "А0267",
        "abbreviation": "267 омбр",
        "corps": "",
        "recipient_to": "Командиру військової частини А0267",
        "destination_where": "м. Тестове",
    },
    OBLAST_TCK: {
        "open_name": OBLAST_TCK,
        "cipher": "",
        "abbreviation": "Рівненський ОТЦК та СП",
        "corps": "",
        "recipient_to": "Начальнику Рівненського обласного ТЦК та СП",
        "destination_where": "м. Рівне",
    },
}

ITEM = (
    "7. Майора МИХАЛЬЦЯ Михайла Михайловича, помічника начальника служби "
    "військової техніки озброєння логістики 267 окремої механізованої бригади "
    "У ЗАПАС ЗА ПІДПУНКТОМ “б” (за станом здоров’я)."
)

# Той самий обліковий рядок, розірваний у різних місцях.
REGISTRATION_SPLITS = [
    ["Підлягає направленню на військовий облік до Вараського РТЦК та СП Рівненської області."],
    ["Підлягає направленню на військовий", "облік до Вараського РТЦК та СП Рівненської області."],
    ["Підлягає направленню на військовий облік", "до Вараського РТЦК та СП Рівненської області."],
    ["Підлягає направленню", "на військовий облік до Вараського РТЦК та СП", "Рівненської області."],
]


@pytest.mark.parametrize(
    "registration",
    REGISTRATION_SPLITS,
    ids=["цілий", "розрив-у-фразі", "розрив-після-облік", "три-уламки"],
)
def test_registration_tck_never_becomes_a_recipient(registration):
    """ТЦК із рядка «Підлягає направленню…» — НЕ адресат (правило 4.2).

    Розрив фрази переносом лишав її хвіст («облік до …ТЦК») у розпорядчому
    тексті, і витяг ішов на ТЦК замість частини.
    """
    lines = [ITEM, "Народився 05 травня 1980 року."] + registration + ["000000000."]
    main_text = _get_item_main_text(lines)

    assert _extract_tck_sender(main_text) is None
    assert "ТЦК" not in main_text


@pytest.mark.parametrize(
    "registration",
    REGISTRATION_SPLITS,
    ids=["цілий", "розрив-у-фразі", "розрив-після-облік", "три-уламки"],
)
def test_extract_goes_to_the_unit_not_to_the_oblast_tck(registration):
    order = (
        "§ 1\n"
        "Відповідно до пункту 3 частини п’ятої статті 26 Закону\n"
        "України “Про військовий обов’язок і військову службу” нижчепойменованих "
        "осіб офіцерського складу ЗВІЛЬНИТИ з військової служби:\n\n"
        + ITEM + "\n"
        + "\n".join(["Народився 05 травня 1980 року."] + registration + ["000000000."])
        + "\n\nКомандир військової частини А0001\nполковник   Петро ТЕСТОВИЙ\n"
    )
    routes = map_military_units(text=order, mapping=MAPPING)

    assert list(routes["unit_paragraphs"]) == ["267 омбр А0267"]


RESERVE_UNIT = "55 батальйон резерву"
OUTER_SUBHEADING = (
    "У ЗАПАС ЗА ПІДПУНКТОМ “б” (за станом здоров’я – за наявності інвалідності):"
)


@pytest.mark.parametrize(
    "item_lines",
    [
        ["5. Капітана ПЕТРЕНКА Петра Петровича, офіцера 55 батальйону резерву, "
         "У ЗАПАС ЗА ПІДПУНКТОМ “г” (через сімейні обставини)."],
        ["5. Капітана ПЕТРЕНКА Петра Петровича, офіцера резерву взводу резерву "
         "офіцерського складу роти резерву офіцерського складу",
         "55 батальйону резерву, У ЗАПАС ЗА ПІДПУНКТОМ “г” (через сімейні обставини)."],
    ],
    ids=["підстава-в-першому-рядку", "підстава-в-другому-рядку"],
)
def test_own_discharge_basis_drops_the_outer_subheading(item_lines):
    """Пункт із ВЛАСНОЮ підставою не тягне чужу зовнішню підшапку.

    Перевірка дивилася лише на перший рядок пункту, тож коли текст розривав
    перенос і «У ЗАПАС ЗА ПІДПУНКТОМ “г”» опинялося на другому рядку, до пункту
    приліплювалася зовнішня підшапка з підпунктом «б» — чужа підстава.
    """
    mapping = {
        RESERVE_UNIT: {
            "open_name": RESERVE_UNIT,
            "cipher": "А0055",
            "abbreviation": "55 бр",
            "corps": "",
            "recipient_to": "Командиру військової частини А0055",
            "destination_where": "м. Тестове",
        }
    }
    order = (
        "§ 1\n"
        "Відповідно до пункту 2 частини четвертої статті 26 Закону України\n"
        "“Про військовий обов’язок і військову службу” нижчепойменованих осіб "
        "офіцерського складу ЗВІЛЬНИТИ з військової служби:\n\n"
        + OUTER_SUBHEADING + "\n\n"
        + "\n".join(item_lines)
        + "\n\nКомандир військової частини А0001\nполковник   Петро ТЕСТОВИЙ\n"
    )
    routes = map_military_units(text=order, mapping=mapping)
    entry = next(iter(routes["unit_paragraphs"].values()))
    heading = entry["items"][0]["parent_heading"]

    assert "ПІДПУНКТОМ “б”" not in heading, heading
    assert "Відповідно до пункту 2" in heading
    assert len(entry["items"][0]["heading_ranges"]) == 2
