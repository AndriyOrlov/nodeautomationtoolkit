"""Тести зворотів-посилань «цієї самої бригади» → «цієї самої військової частини».

Зворот має ставати жіночим родом у ТОМУ Ж відмінку, а підрозділи всередині
частини (рота, взвод, батарея тощо) — лишатися без змін.
"""

import pytest

from nodeautomationtoolkit.builtin_nodes.recipient_mapping import (
    _UNIT_PHRASE_REPLACEMENTS,
    _match_case,
)


def _convert(text: str) -> str:
    result = text
    for pattern, replacer in _UNIT_PHRASE_REPLACEMENTS:
        result = pattern.sub(lambda m: _match_case(m.group(0), replacer(m)), result)
    return result


@pytest.mark.parametrize(
    "source, expected",
    [
        # Родовий
        ("до цієї самої бригади", "до цієї самої військової частини"),
        ("з цього самого батальйону", "з цієї самої військової частини"),
        # Давальний (без прийменника) та місцевий (з прийменником) збігаються
        ("надати цьому самому батальйону", "надати цій самій військовій частині"),
        ("у цьому самому батальйоні", "у цій самій військовій частині"),
        ("на цій самій базі", "на цій самій військовій частині"),
        # Орудний
        ("з цим самим батальйоном", "з цією самою військовою частиною"),
        ("цим самим центром", "цією самою військовою частиною"),
        # Знахідний
        ("у цю саму бригаду", "у цю саму військову частину"),
        # Називний
        ("ця сама бригада", "ця сама військова частина"),
        # Означення «той», «зазначений»
        ("того самого полку", "тієї самої військової частини"),
        ("зазначеного батальйону", "зазначеної військової частини"),
        ("вказаному корпусу", "вказаній військовій частині"),
        # Великі установи
        ("цього самого госпіталю", "цієї самої військової частини"),
        ("цього самого управління", "цієї самої військової частини"),
    ],
)
def test_reference_phrase_keeps_case(source, expected):
    assert _convert(source) == expected


@pytest.mark.parametrize(
    "source",
    [
        # Підрозділи всередині частини — не є військовою частиною
        "цієї самої роти",
        "цього самого взводу",
        "цієї самої батареї",
        "цього самого відділу",
        "цієї самої групи",
        "цього самого штабу",
        "цієї самої ескадрильї",
        # Не підрозділ узагалі
        "цього самого офіцера",
        "цієї самої посади",
        # «та» тут сполучник «і», а не означення
        "полку та бригади",
        # Вже перетворений текст не чіпаємо повторно
        "цієї самої військової частини",
        # ТЦК лишається відкритою назвою
        "цього самого центру комплектування та соціальної підтримки",
    ],
)
def test_reference_phrase_left_untouched(source):
    assert _convert(source) == source


def test_all_caps_is_preserved():
    assert _convert("ЦЬОГО САМОГО БАТАЛЬЙОНУ") == "ЦІЄЇ САМОЇ ВІЙСЬКОВОЇ ЧАСТИНИ"


def test_sentence_initial_capital_is_preserved():
    assert _convert("Ця сама бригада передислокована.") == (
        "Ця сама військова частина передислокована."
    )


def test_particle_zh_is_preserved():
    assert _convert("цієї ж самої бригади") == "цієї ж самої військової частини"


def test_conversion_is_idempotent():
    once = _convert("до цього самого батальйону")
    assert _convert(once) == once


def test_real_order_heading_with_self_reference():
    """Шапка розділу: назва частини шифрується, а зворот у кінці — відмінюється."""
    from nodeautomationtoolkit.builtin_nodes.message_order import generate_decision_order

    mapping = {
        "55 окремий зенітний ракетний полк": {
            "open_name": "55 окремий зенітний ракетний полк",
            "cipher": "А5555",
            "corps": "",
            "abbreviation": "55 озрп",
        }
    }
    text = (
        "§ 2\n"
        "Відповідно до пунктів 82, 83 та 257 Положення про проходження громадянами "
        "України військової служби у Збройних Силах України нижчепойменованих осіб "
        "офіцерського складу 55 окремого зенітного ракетного полку ЗВІЛЬНИТИ з "
        "займаних посад і ПРИЗНАЧИТИ цього самого полку:\n"
    )

    result = generate_decision_order(text=text, mapping=mapping)["decision_text"]

    assert "військової частини А5555" in result
    assert "ПРИЗНАЧИТИ цієї самої військової частини:" in result
    assert "полку" not in result
